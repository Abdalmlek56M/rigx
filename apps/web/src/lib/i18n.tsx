export type Locale = "ar" | "en";
type LocaleContextValue = {
  locale: Locale;
  dir: "rtl" | "ltr";
  messages: Messages;
  toggleLocale: () => void;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);
const storageKey = "hardware-store-locale";
const cookieName = "hardware-store-locale";

export function LocaleProvider({ children, initialLocale = "en" }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocale] = useState<Locale>(initialLocale);

  useEffect(() => {
    const saved = window.localStorage.getItem(storageKey);
    if ((saved === "ar" || saved === "en") && saved !== locale) {
      setLocale(saved);
      document.cookie = `${cookieName}=${saved}; Path=/; Max-Age=31536000; SameSite=Lax`;
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  }, [locale]);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    dir: locale === "ar" ? "rtl" : "ltr",
    messages: locale === "ar" ? ar : en,
    toggleLocale: () => {
      const next = locale === "ar" ? "en" : "ar";
      window.localStorage.setItem(storageKey, next);
      document.cookie = `${cookieName}=${next}; Path=/; Max-Age=31536000; SameSite=Lax`;
      if (
        typeof document !== "undefined" &&
        "startViewTransition" in document &&
        typeof (document as any).startViewTransition === "function" &&
        !window.matchMedia("(prefers-reduced-motion: reduce)").matches
      ) {
        (document as any).startViewTransition(() => {
          setLocale(next);
        });
      } else {
        setLocale(next);
      }
    },
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used inside LocaleProvider.");
  return value;
}
